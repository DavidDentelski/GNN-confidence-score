"""
Appendix D: the GNN's high-confidence failures, behind its deep-cut floor at (9, 9).

At (d, r) = (9, 9) the GNN's post-selected LER stops decreasing below kappa ~ 0.4
(Table III). This step characterizes the GNN failures accepted at small kappa.

From the per-shot arrays (p = 0.005, all eight configurations):
  - accepted failures at kappa = 0.05, 0.1, 0.2, 0.3, 0.4 for the three decoders,
    tie-averaged as in Table III, and the number predicted by each score's own
    calibration, Eq. (5) with the fitted alpha of Table V (with the Poisson
    probability of observing at least as many);
  - at (9, 9), the GNN failures accepted at kappa <= 0.4: their logits, and the
    decisions and gaps of both matching decoders on the same shots.

From the syndromes (needs Linux, Stim and the GNN checkpoints; skipped with a
note when the cache is missing elsewhere): these shots and control groups drawn
from the same 10^8 shots are regenerated by replaying the seeded Stim stream of
generate_shot_data.py, checked against the per-shot arrays (both MWPM decoders
bit-exact, the GNN to the float32 rounding of the original GPU inference), and
compared by the number of detection events (X and Z type, first round, final
readout layer), clusters of detection events joined by single error mechanisms,
distances of the Z-type events to the two boundaries, and the minimum matching
weight of MWPM_uncorr.

Outputs (in --out): derived/high_confidence_arrays.json and
derived/high_confidence_syndromes.json (caches) and high_confidence_failures.md.
"""

import argparse
import json
import os
import sys
import time

import numpy as np
from scipy.stats import poisson

import runs

D9 = (9, 9)
KAPPAS = (0.05, 0.1, 0.2, 0.3, 0.4)
NAMES = {"gnn": "GNN", "mwpmcorr": "MWPM_corr", "mwpm": "MWPM_uncorr"}
CALIB = {"gnn": ("mwpmcorr", "GNN"), "mwpmcorr": ("mwpmcorr", "MWPM"), "mwpm": ("mwpm", "MWPM")}
CONTROLS = {"hi_correct": 3000, "mid_fail": 2000, "random": 2000}
MID_FAIL_MIN_DB = 30.0
SEED = 20261031


def fitted_alpha():
    """alpha of Table V for every score and configuration, from the cached calibration counts."""
    import make_calibration as mc
    out = {}
    for name, (variant, decoder) in CALIB.items():
        mc.configure(variant, os.path.join(runs.BUILD_DIR, variant))
        out[name] = {f"{d},{r}": mc.full_fit(mc.get_binned(d, r), decoder)["alpha"] for d, r in runs.CONFIGS}
    return out


def p_fail(g, alpha):
    return 1.0 / (1.0 + 10.0 ** (alpha * np.asarray(g, dtype=np.float64) / 10.0))


def deep_cut(conf, fail, alpha):
    """Tie-averaged accepted failures (as Table III) and the calibration prediction at each kappa."""
    n = len(conf)
    n_acc = {k: int(np.floor(k * n)) for k in KAPPAS}
    part = np.partition(conf, sorted({n - a for a in n_acc.values()}))
    out = {}
    for k in KAPPAS:
        a = n_acc[k]
        v = float(part[n - a])
        above, at = conf > v, conf == v
        n_above, m_v = int(above.sum()), int(at.sum())
        w = (a - n_above) / m_v
        f_acc = float((fail & above).sum()) + float((fail & at).sum()) * w
        expected = float(p_fail(conf[above], alpha).sum()) + m_v * w * float(p_fail(v, alpha))
        out[str(k)] = {"threshold_db": v, "accepted": a, "failures": f_acc, "ler": f_acc / a,
                       "expected": expected, "p_at_least": float(poisson.sf(round(f_acc) - 1, expected))}
    return out


def array_part():
    alpha = fitted_alpha()
    res = {"alpha": alpha, "configs": {}}
    for d, r in runs.CONFIGS:
        runs.require_arrays(d, r)
        a = {n: np.load(runs.array_path(n, d, r)) for n in NAMES}
        conf = {n: np.abs(x) for n, x in a.items()}
        fail = {n: np.signbit(x) for n, x in a.items()}   # a wrongly decided exact tie is stored as -0.0
        res["configs"][f"{d},{r}"] = {n: deep_cut(conf[n], fail[n], alpha[n][f"{d},{r}"]) for n in NAMES}
        if (d, r) == D9:
            v = res["configs"]["9,9"]["gnn"]["0.4"]["threshold_db"]
            idx = np.flatnonzero(fail["gnn"] & (conf["gnn"] >= v))
            idx = idx[np.argsort(-conf["gnn"][idx])]
            res["deep_failures_9_9"] = [
                {"shot": int(i), "g_gnn": float(conf["gnn"][i]),
                 "kappa_gnn": float(np.mean(conf["gnn"] >= conf["gnn"][i])),
                 "corr_fails": bool(fail["mwpmcorr"][i]), "g_corr": float(conf["mwpmcorr"][i]),
                 "uncorr_fails": bool(fail["mwpm"][i]), "g_uncorr": float(conf["mwpm"][i])} for i in idx]
        print(f"({d},{r}) done", flush=True)
    return res


