def select_shots(deep, threshold_db):
    """The deep failures and the control groups (shot indices into the (9, 9) arrays)."""
    a = np.load(runs.array_path("gnn", *D9))
    g, fail = np.abs(a), np.signbit(a)
    rng = np.random.default_rng(SEED)
    pools = {"hi_correct": ~fail & (g >= threshold_db),                       # GNN correct, same logit range
             "mid_fail": fail & (g >= MID_FAIL_MIN_DB) & (g < threshold_db),  # the GNN's ordinary failures
             "random": np.ones(len(a), bool)}
    groups = {"deep": np.array(sorted(deep), dtype=np.int64)}
    for k, m in pools.items():
        m[groups["deep"]] = False
        idx = np.flatnonzero(m)
        groups[k] = np.sort(rng.choice(idx, size=CONTROLS[k], replace=False))
    return groups


def regenerate(circuit, shots):
    """Detection events and observable flips of the given shots, by replaying the shot stream."""
    from generate_shot_data import CHUNK, seed_for
    sampler = circuit.compile_detector_sampler(seed=seed_for(*D9))
    syn = np.zeros((len(shots), circuit.num_detectors), np.uint8)
    obs = np.zeros(len(shots), np.uint8)
    pos = 0
    for c in range(int(shots[-1] // CHUNK) + 1):
        s, o = sampler.sample(CHUNK, separate_observables=True)
        j = pos + int(np.searchsorted(shots[pos:], (c + 1) * CHUNK))
        if j > pos:
            syn[pos:j], obs[pos:j] = s[shots[pos:j] - c * CHUNK], o[shots[pos:j] - c * CHUNK, 0]
            pos = j
    return syn, obs


class Geometry:
    """Detector types, positions and the detector graph of single error mechanisms."""

    def __init__(self, dem, gnn):
        import stim
        from scipy.sparse import coo_matrix
        self.n = dem.num_detectors
        c = gnn._detector_coords.astype(int)                       # (x, y, t)
        self.x, self.y, self.t = c[:, 0], c[:, 1], c[:, 2]
        self.is_x = gnn._syndrome_mask[self.y, self.x, self.t] == 1   # 1 = X type, 3 = Z type
        self.last = int(self.t.max())                                # final data-qubit readout layer
        rows, cols, b_obs, b_other = [], [], set(), set()
        for inst in dem.flattened():
            if inst.type != "error":
                continue
            comp = []
            for tg in inst.targets_copy() + [stim.target_separator()]:
                if not tg.is_separator():
                    comp.append(tg)
                    continue
                dets = [u.val for u in comp if u.is_relative_detector_id()]
                if len(dets) == 2:
                    rows += dets
                    cols += dets[::-1]
                elif len(dets) == 1:
                    (b_obs if any(u.is_logical_observable_id() for u in comp) else b_other).add(dets[0])
                comp = []
        self.adj = coo_matrix((np.ones(len(rows)), (rows, cols)), shape=(self.n, self.n)).tocsr()
        xy = np.stack([self.x, self.y], 1)

        def distance_to(ids):   # Manhattan distance on the (x, y) grid to the nearest boundary detector
            q = np.unique(xy[sorted(i for i in ids if not self.is_x[i])], axis=0)
            return np.min(np.abs(xy[:, None, :] - q[None, :, :]).sum(-1), axis=1)
        self.d_obs, self.d_other = distance_to(b_obs), distance_to(b_other)

    def features(self, s):
        from scipy.sparse.csgraph import connected_components
        ev = np.flatnonzero(s)
        f = {"n_events": int(len(ev)), "n_X": int(self.is_x[ev].sum()), "n_Z": int((~self.is_x[ev]).sum()),
             "n_first_round": int(np.sum(self.t[ev] == 0)), "n_final_layer": int(np.sum(self.t[ev] == self.last))}
        if len(ev):
            _, lab = connected_components(self.adj[ev][:, ev], directed=False)
            sizes = np.bincount(lab)
            f.update({"n_clusters": int(len(sizes)), "max_cluster": int(sizes.max()),
                      "n_odd_clusters": int(np.sum(sizes % 2))})
        z = ev[~self.is_x[ev]]
        if len(z):
            f.update({"min_dist_obs_boundary": int(self.d_obs[z].min()),
                      "min_dist_other_boundary": int(self.d_other[z].min())})
        return f


def summary(values):
    v = np.asarray([x for x in values if x is not None], float)
    q = np.quantile(v, [0.25, 0.5, 0.75])
    return {"n": int(len(v)), "q25": float(q[0]), "median": float(q[1]), "q75": float(q[2]), "mean": float(v.mean())}


def syndrome_part(arr):
    import torch
    from generate_shot_data import build_circuit, signed_delta
    from correlated_gap import CorrelatedGapDecoder
    from gnn_decoder import GNNDecoder
    from post_selection import MWPMSoftDecoder

    t0 = time.perf_counter()
    torch.set_num_threads(max(1, (os.cpu_count() or 2) // 2))
    v = arr["configs"]["9,9"]["gnn"]["0.4"]["threshold_db"]
    groups = select_shots([x["shot"] for x in arr["deep_failures_9_9"]], v)
    shots = np.unique(np.concatenate(list(groups.values())))
    circuit = build_circuit(*D9, runs.P_MAIN)
    dem = circuit.detector_error_model(decompose_errors=True)
    syn, obs = regenerate(circuit, shots)
    print(f"regenerated {len(shots)} shots ({(time.perf_counter() - t0) / 60:.1f} min)", flush=True)

    mw = MWPMSoftDecoder(dem)
    gnn = GNNDecoder(dem, *D9, runs.model_path(*D9), device="cpu", chunk_size=500)
    new = {"mwpm": signed_delta(mw.decode_with_gap(syn)[1], obs[:, None]),
           "mwpmcorr": signed_delta(CorrelatedGapDecoder(dem).decode_with_gap(syn)[1], obs[:, None]),
           "gnn": signed_delta(gnn.decode_with_gap(syn)[1], obs[:, None])}
    saved = {n: np.load(runs.array_path(n, *D9), mmap_mode="r")[shots] for n in NAMES}
    check = {}
    for n in NAMES:
        diff = np.abs(new[n].astype(np.float64) - saved[n])
        check[n] = {"shots": int(len(shots)), "not_bit_identical": int(np.sum(new[n] != saved[n])),
                    "decision_mismatch": int(np.sum(np.signbit(new[n]) != np.signbit(saved[n]))),
                    "max_abs_diff_db": float(diff.max()),
                    "within_float32_rounding": bool(np.all(diff <= 1e-3 + 1e-5 * np.abs(saved[n])))}
    ok = (check["mwpm"]["not_bit_identical"] == 0 and check["mwpmcorr"]["not_bit_identical"] == 0
          and check["gnn"]["decision_mismatch"] == 0 and check["gnn"]["within_float32_rounding"])
    if not ok:
        raise RuntimeError(f"regenerated shots do not reproduce the per-shot arrays: {check}")

    n = len(shots)
    w0 = mw._matching.decode_batch(np.concatenate([syn, np.zeros((n, 1), np.uint8)], 1), return_weights=True)[1]
    w1 = mw._matching.decode_batch(np.concatenate([syn, np.ones((n, 1), np.uint8)], 1), return_weights=True)[1]
    geo = Geometry(dem, gnn)
    rows = {}
    for i, s in enumerate(shots):
        f = geo.features(syn[i])
        f.update({"obs": int(obs[i]), "g_gnn": float(abs(saved["gnn"][i])), "g_corr": float(abs(saved["mwpmcorr"][i])),
                  "corr_fails": bool(np.signbit(saved["mwpmcorr"][i])), "uncorr_fails": bool(np.signbit(saved["mwpm"][i])),
                  "min_matching_weight_nats": float(min(w0[i], w1[i]))})
        rows[int(s)] = f
    keys = ["n_events", "n_X", "n_Z", "n_first_round", "n_final_layer", "n_clusters", "max_cluster",
            "n_odd_clusters", "min_dist_obs_boundary", "min_dist_other_boundary", "min_matching_weight_nats",
            "g_gnn", "g_corr"]
    comparison = {}
    for gname, idx in groups.items():
        rs = [rows[int(s)] for s in idx]
        comparison[gname] = {k: summary([r.get(k) for r in rs]) for k in keys}
        comparison[gname].update({k: float(np.mean([r[k] for r in rs])) for k in ("corr_fails", "uncorr_fails", "obs")})
    return {"validation": check, "group_sizes": {k: int(len(x)) for k, x in groups.items()},
            "controls": {"hi_correct": f"GNN correct, g_GNN >= {v:.2f} dB (kappa = 0.4 threshold)",
                         "mid_fail": f"GNN fails, {MID_FAIL_MIN_DB:.0f} dB <= g_GNN < {v:.2f} dB",
                         "random": "all shots"},
            "comparison": comparison, "deep_failures": [rows[int(s)] for s in groups["deep"]],
            "minutes": (time.perf_counter() - t0) / 60}


