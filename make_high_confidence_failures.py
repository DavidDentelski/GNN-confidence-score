def write_md(arr, syn, out):
    c9 = arr["configs"]["9,9"]
    deep = arr["deep_failures_9_9"]
    top5 = [x for x in deep if x["g_gnn"] >= c9["gnn"]["0.05"]["threshold_db"]]
    corr_fail = [x for x in deep if x["corr_fails"]]
    L = ["# High-confidence failures of the GNN (Appendix D)", "",
         "Generated by make_high_confidence_failures.py; p = 0.005, 10^8 shots per configuration.", "",
         "## Accepted failures at deep cuts: observed / predicted by the score's own calibration (Eq. (5), alpha of Table V)",
         "", "| (d, r) | decoder | " + " | ".join(f"kappa = {k}" for k in KAPPAS) + " | L(0.2)/L(0.4) |",
         "|---|---|" + "---|" * (len(KAPPAS) + 1)]
    for key, res in arr["configs"].items():
        for n in NAMES:
            x = res[n]
            ratio = x["0.2"]["ler"] / x["0.4"]["ler"] if x["0.4"]["ler"] else float("nan")
            L.append(f"| ({key}) | {NAMES[n]} | " + " | ".join(
                f"{x[str(k)]['failures']:.0f} / {x[str(k)]['expected']:.1f}" for k in KAPPAS) + f" | {ratio:.2f} |")
    L += ["", "Poisson probability of at least the observed GNN failures at kappa = 0.1, given the prediction: " +
          ", ".join(f"({k}) {r['gnn']['0.1']['p_at_least']:.2g}" for k, r in arr["configs"].items()), "",
          "## (9, 9): the GNN failures accepted at kappa <= 0.4", "",
          f"- acceptance thresholds g_GNN: " + ", ".join(f"kappa = {k}: {c9['gnn'][str(k)]['threshold_db']:.1f} dB" for k in KAPPAS),
          f"- acceptance thresholds g_corr: " + ", ".join(f"kappa = {k}: {c9['mwpmcorr'][str(k)]['threshold_db']:.1f} dB" for k in KAPPAS),
          f"- GNN failures with g_GNN >= kappa-0.4 threshold: {len(deep)}; among the 5% most confident shots: {len(top5)}, "
          f"g_GNN {min(x['g_gnn'] for x in top5):.1f}--{max(x['g_gnn'] for x in top5):.1f} dB",
          f"- MWPM_corr fails on {len(corr_fail)} of the {len(deep)}, MWPM_uncorr on {sum(x['uncorr_fails'] for x in deep)}, "
          f"both on {sum(x['corr_fails'] and x['uncorr_fails'] for x in deep)}",
          f"- g_corr on these shots: median {np.median([x['g_corr'] for x in deep]):.1f} dB "
          f"(on the {len(corr_fail)} MWPM_corr failures: median {np.median([x['g_corr'] for x in corr_fail]):.1f} dB, "
          f"max {max(x['g_corr'] for x in corr_fail):.1f} dB)", "",
          "| shot | g_GNN (dB) | kappa_GNN | MWPM_corr fails | g_corr (dB) | MWPM_uncorr fails | g_uncorr (dB) |",
          "|---|---|---|---|---|---|---|"]
    L += [f"| {x['shot']} | {x['g_gnn']:.1f} | {x['kappa_gnn']:.4f} | {x['corr_fails']} | {x['g_corr']:.1f} | "
          f"{x['uncorr_fails']} | {x['g_uncorr']:.1f} |" for x in deep]
    L += ["", "## (9, 9): syndrome features (median [q25, q75])", ""]
    if syn is None:
        L.append("Not computed: needs the regenerated syndromes (Linux, Stim, GNN checkpoints).")
    else:
        L += [f"Regenerated shots reproduce the per-shot arrays: {json.dumps(syn['validation'])}", "",
              "Groups: deep = the GNN failures above; " + "; ".join(f"{k} = {v}" for k, v in syn["controls"].items()), ""]
        groups = list(syn["comparison"])
        L += ["| feature | " + " | ".join(f"{g} (n = {syn['group_sizes'][g]})" for g in groups) + " |",
              "|---|" + "---|" * len(groups)]
        for k, s in syn["comparison"]["deep"].items():
            if isinstance(s, dict):
                L.append(f"| {k} | " + " | ".join(
                    f"{syn['comparison'][g][k]['median']:.3g} [{syn['comparison'][g][k]['q25']:.3g}, "
                    f"{syn['comparison'][g][k]['q75']:.3g}]" for g in groups) + " |")
            else:
                L.append(f"| fraction {k} | " + " | ".join(f"{syn['comparison'][g][k]:.2f}" for g in groups) + " |")
    open(os.path.join(out, "high_confidence_failures.md"), "w").write("\n".join(L) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=os.path.join(runs.BUILD_DIR, "high_confidence"))
    a = ap.parse_args()
    os.makedirs(os.path.join(a.out, "derived"), exist_ok=True)
    cache_arr = os.path.join(a.out, "derived", "high_confidence_arrays.json")
    cache_syn = os.path.join(a.out, "derived", "high_confidence_syndromes.json")
    if os.path.exists(cache_arr):
        arr = json.load(open(cache_arr))
    else:
        arr = array_part()
        json.dump(arr, open(cache_arr, "w"), indent=1)
    syn = None
    if os.path.exists(cache_syn):
        syn = json.load(open(cache_syn))
    elif sys.platform.startswith("linux"):
        syn = syndrome_part(arr)
        json.dump(syn, open(cache_syn, "w"), indent=1)
    else:
        print("syndrome features skipped: the shot stream is regenerated only on Linux", flush=True)
    write_md(arr, syn, a.out)
    print(f"wrote {os.path.join(a.out, 'high_confidence_failures.md')}", flush=True)


if __name__ == "__main__":
    main()
